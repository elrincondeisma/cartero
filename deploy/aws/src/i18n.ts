export type Lang = 'es' | 'en'

let current: Lang = 'es'
export const lang = () => current

/** Mensajes del idioma activo (se rellena con setLang). */
export const m: Messages = { ...es }

export function setLang(lang: Lang): void {
  current = lang
  Object.assign(m, lang === 'en' ? en : es)
}

export function detectLang(env: NodeJS.ProcessEnv = process.env): Lang {
  const v = env.LC_ALL || env.LC_MESSAGES || env.LANG || Intl.DateTimeFormat().resolvedOptions().locale
  return /^es/i.test(v ?? '') ? 'es' : 'en'
}

